function normalizeSearchText(text) {
  return String(text || '')
    .toLowerCase()
    .replace(/ё/g, 'е')
    .trim();
}

function matchesChampionSearch(name, query) {
  if (!query) return true;

  var nameNorm = normalizeSearchText(name);
  var q = normalizeSearchText(query);

  if (nameNorm.indexOf(q) !== -1) return true;

  for (var alias in SEARCH_ALIASES) {
    if (!Object.prototype.hasOwnProperty.call(SEARCH_ALIASES, alias)) continue;
    if (alias.indexOf(q) !== 0 && q.indexOf(alias) !== 0) continue;

    var terms = SEARCH_ALIASES[alias];
    for (var i = 0; i < terms.length; i++) {
      if (nameNorm.indexOf(terms[i]) !== -1) return true;
    }
  }

  return false;
}
